"""Train all ML models, write metrics.json, and publish a human-readable
evaluation report (docs/ML_EVALUATION.md).

Run:
    python -m app.ml.train_all                              # synthetic crime index
    python -m app.ml.train_all --crime-index-source ncrb    # real NCRB-calibrated index
    python -m app.ml.train_all --if-missing                 # only train when artifacts are absent
                                                            # (used by entrypoint.sh on first start)
"""
import argparse
import json
import os
from datetime import UTC, datetime

from app.ml import train_anomaly, train_safety, train_zones

REQUIRED_ARTIFACTS = ("anomaly_isoforest.joblib", "anomaly_scaler.joblib", "safety_rf.joblib")
DEFAULT_REPORT = os.path.join("..", "docs", "ML_EVALUATION.md")


def artifacts_present(models_dir: str = "ml_models") -> bool:
    return all(os.path.exists(os.path.join(models_dir, f)) for f in REQUIRED_ARTIFACTS)


def render_report(report: dict, crime_index_source: str) -> str:
    a, s, z = report["anomaly"], report["safety"], report["zones"]
    cm = a["confusion_matrix"]
    prov = s.get("data_provenance", {})
    imp = "\n".join(f"| {k} | {v} |" for k, v in sorted(s["feature_importances"].items(), key=lambda kv: -kv[1]))
    prov_rows = "\n".join(f"| {k} | {v} |" for k, v in prov.items())
    a_prov = a.get("data_provenance", {})
    a_real = a.get("data_source") == "geolife"
    return f"""# ML Evaluation Report

Generated by `python -m app.ml.train_all --crime-index-source {crime_index_source}`
on {datetime.now(UTC).strftime('%Y-%m-%d %H:%M UTC')}. Regenerate it any time by re-running that command.

> **Read this honestly.**
> - **Anomaly detection:** {"normal movement is **real** (GeoLife GPS trajectories, re-sampled at this app's ping rate); the emergencies it is scored against are **simulated**, because no public dataset has labelled real ones. Precision/recall below say how well it separates real normal travel from those simulated emergencies." if a_real else "trained on *synthetic* data, so the scores measure how well it learns the generator's rules, not real-world accuracy."}
> - **Safety score:** the app scores with the published weighted formula by default
>   (`SAFETY_SCORE_MODE=formula`), fed with **real** inputs at run time -- NCRB district crime
>   (app/services/district_crime.py) and live weather (Open-Meteo / OpenWeatherMap). The
>   RandomForest below is trained on synthetic rows to reproduce that formula and is only
>   used with `SAFETY_SCORE_MODE=model`; its R² measures how well it copies the formula.
> - Fall detection is evaluated separately on real recordings: docs/FALL_DETECTION_EVALUATION.md.

## 1. Anomaly detection — {a['model']}

| Metric | Value |
|---|---|
| Normal movement | {a_prov.get('normal', 'synthetic')} |
| Anomalies | {a_prov.get('anomalies', 'simulated')} |
| Features | {', '.join(a['features'])} |
| Train / test rows | {a['n_train']} / {a['n_test']} |
| Contamination | {a['contamination']} |
| Precision | {a['precision']} |
| Recall | {a['recall']} |
| F1 | {a['f1']} |
| ROC-AUC | {a['roc_auc']} |

Confusion matrix (test set): TN={cm['true_negative']}, FP={cm['false_positive']}, FN={cm['false_negative']}, TP={cm['true_positive']}.

## 2. Safety score — {s['model']}

| Metric | Value |
|---|---|
| Train / test rows | {s['n_train']} / {s['n_test']} |
| R² | {s['r2']} |
| MAE (points on 0–100) | {s['mae']} |
| Baseline MAE (predict the mean) | {s['baseline_mae']} |

Feature importances:

| Feature | Importance |
|---|---|
{imp}

Data provenance:

| Feature | Source |
|---|---|
{prov_rows}

## 3. Hot-zone discovery — {z['model']}

| Metric | Value |
|---|---|
| Points clustered | {z['n_points']} |
| Clusters found | {z['n_clusters']} |
| Noise points | {z['n_noise']} |
| eps (deg) / min_samples | {z['eps_deg']} / {z['min_samples']} |
| Silhouette | {z['silhouette']} |
"""


def main(models_dir: str = "ml_models", crime_index_source: str = "uniform",
         report_path: str | None = DEFAULT_REPORT, movement_source: str = "auto") -> None:
    os.makedirs(models_dir, exist_ok=True)
    report = {
        "anomaly": train_anomaly.train(models_dir, movement_source=movement_source),
        "safety": train_safety.train(models_dir, crime_index_source=crime_index_source),
        "zones": train_zones.train(models_dir),
    }
    with open(os.path.join(models_dir, "metrics.json"), "w") as f:
        json.dump(report, f, indent=2)
    if report_path:
        os.makedirs(os.path.dirname(os.path.abspath(report_path)), exist_ok=True)
        with open(report_path, "w", encoding="utf-8") as f:
            f.write(render_report(report, crime_index_source))
        print(f"Evaluation report written to {report_path}")
    print("\n=== All models trained. metrics.json written. ===")


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--models-dir", default="ml_models")
    p.add_argument("--crime-index-source", choices=["uniform", "ncrb"], default="uniform")
    p.add_argument("--movement-source", choices=["auto", "geolife", "synthetic"], default="auto",
                   help="normal movement for the anomaly model: real GeoLife traces when "
                        "data/real/geolife_movement.csv.gz exists (auto), or synthetic")
    p.add_argument("--report-path", default=DEFAULT_REPORT, help="'' to skip writing the report")
    p.add_argument("--if-missing", action="store_true",
                   help="Skip training when the model artifacts already exist")
    args = p.parse_args()
    if args.if_missing and artifacts_present(args.models_dir):
        print("ML artifacts already present; skipping training.")
    else:
        main(args.models_dir, args.crime_index_source, args.report_path or None,
             movement_source=args.movement_source)
